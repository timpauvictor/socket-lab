#!/usr/bin/env python3
"""Build results/eval-board.xlsx from results/eval-board.csv (the canonical table).

Usage: python reporting/build_board.py   (run from the repo root)
"""
import argparse
import csv
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parents[1] / "results"
CSV_PATH = ROOT / "eval-board.csv"
XLSX_PATH = ROOT / "eval-board.xlsx"

HEADER_FILL = PatternFill("solid", fgColor="1F4E78")
HEADER_FONT = Font(bold=True, color="FFFFFF")
PENDING_FILL = PatternFill("solid", fgColor="FFF2CC")
TITLE_FONT = Font(bold=True, size=13)


def main(output=XLSX_PATH):
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    # Delta vs floor per pair (floors only; smoke excluded).
    floors = {}
    for r in rows:
        if r["setup"] == "base" and r["chrf"]:
            floors[r["pair"]] = float(r["chrf"])

    wb = Workbook()
    ws = wb.active
    ws.title = "chrF board"
    ws["A1"] = "Qwen3-0.6B translation eval board (sacreBLEU chrF, FLORES devtest n=1012 unless noted)"
    ws["A1"].font = TITLE_FONT
    headers = ["Pair", "Setup", "n", "chrF", "Delta vs floor", "Eval file", "Adapters", "Notes"]
    ws.append(headers)
    for cell in ws[2]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center", wrap_text=True)

    for r in rows:
        chrf = float(r["chrf"]) if r["chrf"] else None
        base = floors.get(r["pair"])
        if chrf is None:
            delta = "pending"
        elif r["setup"] == "base" or r["setup"] == "task-only" and r["n"] == "10":
            delta = "n/a"
        elif base is None:
            delta = "no floor yet"
        else:
            delta = round(chrf - base, 2)
        ws.append([r["pair"], r["setup"], r["n"] if r["n"] else "pending",
                   chrf if chrf is not None else "pending",
                   delta, r["eval_file"], r["adapters"], r["notes"]])
        if chrf is None:
            for cell in ws[ws.max_row]:
                cell.fill = PENDING_FILL

    widths = [10, 22, 8, 8, 14, 38, 52, 52]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A3"

    about = wb.create_sheet("About")
    about_lines = [
        ("Metric", "sacreBLEU chrF, signature nrefs:1|case:mixed|eff:yes|nc:6|nw:0|space:no|version:2.6.0"),
        ("Base model", "Qwen3-0.6B-Base Q8_0 GGUF, local llama.cpp server"),
        ("Eval harness", "evaluation/eval_llama.py via run_eval.py (raw /v1/completions, temp 0)"),
        ("Task adapter", "adapters/task-full-lora.gguf (PEFT r32 -> GGUF f16, 224 tensors)"),
        ("Box adapters", "adapters/box-ro-lora.gguf, box-en-lora.gguf (rank 16, 9.18MB each)"),
        ("Stacking", "single comma-joined --lora flag (b11146 keeps only the last of repeated flags)"),
        ("Loop diagnostic", "evaluation/loop_check.py: at least 24 whitespace-separated words and an 8-word window repeated 3+ times. This measures repetition, not EOS or token-limit termination."),
        ("Status", "EOS-tuned monolith and de-fr direct/pivot runs are recorded. The task-only ro-en row has only 10 examples; it is not a full comparison."),
        ("Provenance limits", "Historical headers omit adapter identity, decoding limits, strategy and finish reason. Consult the journal and CSV; do not treat all rows as controlled comparisons."),
        ("Source of truth", "eval-board.csv in this folder; this workbook is generated by reporting/build_board.py"),
    ]
    about["A1"] = "Notes"
    about["A1"].font = TITLE_FONT
    for k, v in about_lines:
        about.append([k, v])
    about.column_dimensions["A"].width = 18
    about.column_dimensions["B"].width = 110
    for row in about.iter_rows(min_row=2, max_col=1):
        for cell in row:
            cell.font = Font(bold=True)

    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output)
    print(f"Wrote {output} ({len(rows)} data rows)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=XLSX_PATH)
    main(parser.parse_args().output)
